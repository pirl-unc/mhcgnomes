#!/usr/bin/env python3
"""
Generate mhcgnomes/data/single_field_alleles.yaml from pinned registry releases.

In IMGT/HLA and IPD-MHC nomenclature the first field of an allele name is the
allele group (or lineage) and the second names a specific protein, so a name
with one numeric field, such as HLA-A*02, usually denotes a group. A few
complete allele names have a single numeric field all the same, e.g.
HLA-MICA*001 or Papa-B*03. Allele.is_allele_group (#215) reads this file so
that it does not call those groups.

Only names whose single field is numeric (optionally after IPD-MHC's "W"
prefix, an allele not yet assigned to a locus) are written: a single field with
letters (H2-K*b, Rano-A1*f) is never read as a group, so it needs no entry.

Inputs are the checksum-pinned files of the "allele-aliases" download group,
the same ones combine_allele_aliases.sh uses:

    python -m mhcgnomes data download --group allele-aliases
    python scripts/generate_single_field_alleles.py

CI regenerates the file and fails if the committed copy differs.
"""

import argparse
import re
from collections import defaultdict
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
EXTERNAL = REPO_ROOT / ".external-data"
IMGT_HISTORY = EXTERNAL / "IMGT-HLA-Allelelist-history-3.42.0.txt"
IPD_XML = EXTERNAL / "IPD-MHC-3.8.0.0.xml"
OUTPUT = REPO_ROOT / "mhcgnomes" / "data" / "single_field_alleles.yaml"

# Expression and status suffixes that can follow the last field (N, L, S, C,
# A, Q; IPD-MHC's Ps, Sp and BoLA's SV). They do not change the field count.
_SUFFIX = re.compile(r"(Ps|Sp|SV|[NLSCAQ])$")

HEADER = """\
# GENERATED by scripts/generate_single_field_alleles.py -- do not edit by hand.
#
# Complete allele names whose only field is numeric, from IPD-IMGT/HLA 3.42.0
# (Allelelist_history.txt, current column) and IPD-MHC 3.8.0.0 (XML entry
# names). Each names one allele, although a single numeric field usually names
# an allele group (HLA-A*02). Allele.is_allele_group reads this file (#215).
"""


def current_imgt_names(path):
    """Current allele names from IPD-IMGT/HLA's Allelelist_history.txt."""
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or line.startswith("HLA_ID"):
                continue
            columns = line.rstrip("\n").split(",")
            # Column 1 is the newest release; an empty cell means deleted.
            if len(columns) > 1 and columns[1]:
                yield "HLA", columns[1]


def ipd_mhc_names(path):
    """Allele names (prefix, gene*fields) from an IPD-MHC XML release."""
    text = Path(path).read_text(encoding="utf-8")
    for name in re.findall(r'<entry id="[^"]+">\s*<name>([^<]+)</name>', text):
        prefix, _, rest = name.partition("-")
        if rest:
            yield prefix, rest


def single_field_alleles(names):
    """Group the names with one all-digit field by prefix and gene."""
    result = defaultdict(lambda: defaultdict(set))
    for prefix, name in names:
        if "*" not in name:
            continue
        gene, fields = name.split("*", 1)
        fields = _SUFFIX.sub("", fields)
        if ":" not in fields and re.fullmatch(r"[Ww]?\d+", fields):
            result[prefix][gene].add(fields)
    return {
        prefix: {gene: sorted(fields) for gene, fields in sorted(genes.items())}
        for prefix, genes in sorted(result.items())
    }


def to_yaml(table):
    """
    Write every field as a double-quoted string. Left bare, PyYAML emits 028
    unquoted (a string to YAML 1.1, the integer 28 to YAML 1.2 parsers).
    """
    lines = []
    for prefix, genes in table.items():
        lines.append(f'"{prefix}":')
        for gene, fields in genes.items():
            lines.append(f'  "{gene}":')
            lines.extend(f'    - "{field}"' for field in fields)
    text = "\n".join(lines) + "\n"
    # Guard the hand-rolled format: it must load back to the same table.
    assert yaml.safe_load(text) == table
    return text


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--imgt-history", type=Path, default=IMGT_HISTORY)
    parser.add_argument("--ipd-xml", type=Path, default=IPD_XML)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)

    names = [*current_imgt_names(args.imgt_history), *ipd_mhc_names(args.ipd_xml)]
    table = single_field_alleles(names)
    args.output.write_text(HEADER + to_yaml(table), encoding="utf-8")
    count = sum(len(fields) for genes in table.values() for fields in genes.values())
    print(f"Wrote {count} single-field allele names across {len(table)} prefixes to {args.output}")


if __name__ == "__main__":
    main()
