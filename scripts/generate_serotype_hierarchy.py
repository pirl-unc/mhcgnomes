#!/usr/bin/env python3
"""Generate the HLA broad/split graph from the verified, pinned WMDA source."""

import argparse
from pathlib import Path

import yaml

from mhcgnomes.external_data import is_verified, load_manifest
from mhcgnomes.serotype_hierarchy import serotype_descendants

ROOT = Path(__file__).resolve().parent.parent
SOURCE_ID = "imgt-hla-serotype-relations-3.66.0"
OUTPUT = ROOT / "mhcgnomes/data/serotype_splits.yaml"


def parse_serotype_relationships(text: str) -> dict[str, list[str]]:
    """Read WMDA rel_ser_ser.txt, returning direct broad-to-split edges.

    Each non-comment row has locus;antigen;splits;associated-antigens. Only the
    third field establishes a split; the fourth is not an allele assignment.
    Malformed rows, repeated antigens and invalid graphs raise ValueError.
    The file format is documented at https://hla.alleles.org/pages/wmda/wmda/.
    """
    graph = {}
    seen = set()
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split(";")
        if len(fields) != 4:
            raise ValueError(f"Expected four WMDA fields on line {number}")
        locus, antigen, split_field, _associated = fields
        if not locus.isalpha() or not antigen.isdigit():
            raise ValueError(f"Invalid WMDA antigen on line {number}")
        name = locus + antigen
        if name in seen:
            raise ValueError(f"Repeated WMDA antigen {name}")
        seen.add(name)
        if split_field:
            children = split_field.split("/")
            if not all(child.isdigit() for child in children):
                raise ValueError(f"Invalid WMDA split on line {number}")
            graph[name] = sorted(locus + child for child in children)
    serotype_descendants(graph)
    return dict(sorted(graph.items()))


def main(argv=None):
    """Verify the pinned input hash and write a deterministic, cited YAML graph."""
    source = next(source for source in load_manifest() if source.id == SOURCE_ID)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / ".external-data" / source.filename)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    if not is_verified(args.input, source.sha256):
        parser.error(
            "Input is missing or fails its pinned SHA256; run mhcgnomes data download --group serotype-hierarchy"
        )
    graph = parse_serotype_relationships(args.input.read_text(encoding="utf-8"))
    header = (
        "# Generated by scripts/generate_serotype_hierarchy.py; do not edit.\n"
        f"# IPD-IMGT/HLA {source.release}: {source.url}\n"
        f"# SHA256: {source.sha256}\n"
        "# WMDA column 3: broad -> split antigens, NOT associated-antigen column 4.\n"
        "# Format and meaning: https://hla.alleles.org/pages/wmda/wmda/\n"
    )
    args.output.write_text(
        header + yaml.safe_dump({"HLA": graph}, sort_keys=True), encoding="utf-8"
    )
    print(f"Wrote {len(graph)} broads and {sum(map(len, graph.values()))} split edges")


if __name__ == "__main__":
    main()
